"""Render bounded Markdown only from a fully validated release evidence bundle."""

from __future__ import annotations

import json
from pathlib import Path
from typing import cast

from evaluation.deterministic_release import validate_deterministic_release_artifact
from evaluation.evidence import (
    validate_evidence_manifest,
    validate_naive_pairs_bundle,
    validate_secure_smokes_bundle,
)

JsonObject = dict[str, object]

_REQUIRED_FILES = (
    "manifest.json",
    "deterministic-summary.json",
    "naive-pairs.jsonl",
    "secure-smokes.jsonl",
    "deterministic.manifest.json",
    "secure-smokes.manifest.json",
)


def render_release_results(evidence_directory: Path) -> str:
    """Validate all six release files and return deterministic Markdown tables."""

    root = evidence_directory.resolve()
    paths = {name: root / name for name in _REQUIRED_FILES}
    missing = [name for name, path in paths.items() if not path.is_file()]
    if missing:
        raise ValueError("release evidence is missing one or more required files")

    aggregate = _load_object(paths["manifest.json"])
    deterministic_sidecar = _load_object(paths["deterministic.manifest.json"])
    secure_sidecar = _load_object(paths["secure-smokes.manifest.json"])
    for name in ("manifest.json", "deterministic.manifest.json", "secure-smokes.manifest.json"):
        validate_evidence_manifest(paths[name])
    deterministic = validate_deterministic_release_artifact(paths["deterministic-summary.json"])
    validate_naive_pairs_bundle(paths["naive-pairs.jsonl"])
    fixture_commitments = {
        _string(item.get("path"), "fixture path"): _string(item.get("sha256"), "fixture hash")
        for item in _objects(secure_sidecar.get("fixtures"), "secure fixtures")
    }
    validate_secure_smokes_bundle(
        paths["secure-smokes.jsonl"],
        fixture_commitments=fixture_commitments,
    )
    _validate_release_linkage(
        aggregate,
        deterministic_sidecar,
        secure_sidecar,
        paths["naive-pairs.jsonl"],
    )

    naive_rows = _load_jsonl(paths["naive-pairs.jsonl"])
    bundle = next(row for row in naive_rows if row.get("event") == "paired_bundle_summary")
    series = {
        _string(row.get("evaluation_kind"), "evaluation kind"): _object(
            row.get("summary"), "series summary"
        )
        for row in naive_rows
        if row.get("event") == "paired_summary"
    }
    secure_rows = _load_jsonl(paths["secure-smokes.jsonl"])
    heldout_clean_runs = [
        row
        for row in secure_rows
        if row.get("event") == "heldout_mapper_run" and row.get("condition") == "clean"
    ]

    attack = series["attack_pair"]
    control = series["clean_control"]
    implementation_hash = _string(
        aggregate.get("implementation_tree_sha256"), "implementation hash"
    )
    lines = [
        "<!-- Generated by `python -m evaluation render-results`; do not edit manually. -->",
        "",
        "### Release evidence summary",
        "",
        "| Evidence | Scope | Result |",
        "|---|---:|---|",
        (
            f"| Deterministic secure suite | {deterministic.case_count} cases / "
            f"{deterministic.invariant_count} invariants | "
            f"{'PASS' if deterministic.passed else 'FAIL'} |"
        ),
        (
            f"| Naïve attack pairs | {_integer(attack.get('pair_count'), 'attack pairs')} | "
            f"{_integer(attack.get('valid_pair_count'), 'valid attack pairs')} valid |"
        ),
        (
            f"| Naïve clean/control pairs | {_integer(control.get('pair_count'), 'control pairs')} "
            f"| {_integer(control.get('valid_pair_count'), 'valid control pairs')} valid |"
        ),
        *_live_result_rows(secure_rows),
        "",
        "### Naïve baseline metrics",
        "",
        "| Series | Valid denominator | Positive rank gains | Rank-one entries | Failed attempts |",
        "|---|---:|---:|---:|---:|",
        _naive_metric_row("Registered attack", attack),
        _naive_metric_row("Clean/control", control),
        "",
        "### Bound threat and live safety",
        "",
        "| Field | Value |",
        "|---|---|",
        f"| Attack fixture | `{_string(bundle.get('attack_fixture_id'), 'attack fixture')}` |",
        f"| Threat class | `{_string(bundle.get('threat_class'), 'threat class')}` |",
        (
            "| Attacker knowledge | "
            f"`{_string(bundle.get('attacker_knowledge_level'), 'attacker knowledge')}` |"
        ),
        (
            "| Held-out clean utility observation | "
            f"{sum(row.get('utility_observation_met') is True for row in heldout_clean_runs)}"
            f"/{len(heldout_clean_runs)} runs met |"
        ),
        f"| Implementation tree | `{implementation_hash}` |",
        "",
    ]
    return "\n".join(lines)


def _live_result_rows(rows: tuple[JsonObject, ...]) -> tuple[str, ...]:
    """Render completion separately from acceptance for each live protocol arm."""

    canonical_runs = [row for row in rows if row.get("event") == "canonical_secure_run"]
    canonical_pairs = [row for row in rows if row.get("event") == "canonical_secure_pair"]
    heldout_runs = [row for row in rows if row.get("event") == "heldout_mapper_run"]
    heldout_pairs = [row for row in rows if row.get("event") == "heldout_mapper_pair"]

    canonical_evaluable = {
        _integer(row.get("repetition"), "canonical repetition")
        for row in canonical_pairs
        if row.get("both_individually_accepted") is True
    }
    heldout_successes: dict[int, set[str]] = {}
    for row in heldout_runs:
        if row.get("status") != "success":
            continue
        repetition = _integer(row.get("repetition"), "held-out repetition")
        condition = _string(row.get("condition"), "held-out condition")
        heldout_successes.setdefault(repetition, set()).add(condition)
    heldout_evaluable = {
        repetition
        for repetition, conditions in heldout_successes.items()
        if conditions == {"clean", "directive"}
    }

    canonical_passed = sum(
        row.get("status") == "passed"
        and _integer(row.get("repetition"), "canonical repetition") in canonical_evaluable
        for row in canonical_pairs
    )
    heldout_passed = sum(
        row.get("status") == "passed"
        and _integer(row.get("repetition"), "held-out repetition") in heldout_evaluable
        for row in heldout_pairs
    )
    return (
        (
            f"| Canonical secure live runs | {len(canonical_runs)} | "
            f"{sum(row.get('status') == 'success' for row in canonical_runs)} successful |"
        ),
        (
            f"| Canonical secure live pairs | {len(canonical_pairs)} | "
            f"{canonical_passed} passed / {len(canonical_evaluable)} evaluable / "
            f"{len(canonical_pairs) - len(canonical_evaluable)} not evaluable |"
        ),
        (
            f"| Held-out mapper live runs | {len(heldout_runs)} | "
            f"{sum(row.get('status') == 'success' for row in heldout_runs)} successful |"
        ),
        (
            f"| Held-out mapper safety pairs | {len(heldout_pairs)} | "
            f"{heldout_passed} passed / {len(heldout_evaluable)} evaluable / "
            f"{len(heldout_pairs) - len(heldout_evaluable)} not evaluable |"
        ),
    )


def _naive_metric_row(label: str, summary: JsonObject) -> str:
    return (
        f"| {label} | {_integer(summary.get('metric_denominator'), 'metric denominator')} | "
        f"{_integer(summary.get('positive_rank_gain_count'), 'positive rank gains')} | "
        f"{_integer(summary.get('target_rank_one_entry_count'), 'rank-one entries')} | "
        f"{_integer(summary.get('failed_attempt_count'), 'failed attempts')} |"
    )


def _validate_release_linkage(
    aggregate: JsonObject,
    deterministic_sidecar: JsonObject,
    secure_sidecar: JsonObject,
    naive_path: Path,
) -> None:
    expected_artifacts = {
        "deterministic-summary.json",
        "deterministic.manifest.json",
        "naive-pairs.jsonl",
        "secure-smokes.manifest.json",
    }
    artifact_names = {
        _string(item.get("path"), "artifact path")
        for item in _objects(aggregate.get("artifacts"), "aggregate artifacts")
    }
    live_names = {
        _string(item.get("path"), "live artifact path")
        for item in _objects(aggregate.get("live_artifacts"), "aggregate live artifacts")
    }
    if artifact_names != expected_artifacts or live_names != {"secure-smokes.jsonl"}:
        raise ValueError("aggregate manifest does not bind the exact six-file release bundle")
    implementation_hash = _string(
        aggregate.get("implementation_tree_sha256"), "implementation hash"
    )
    if any(
        sidecar.get("implementation_tree_sha256") != implementation_hash
        for sidecar in (deterministic_sidecar, secure_sidecar)
    ):
        raise ValueError("release evidence sidecars do not share one implementation tree")
    naive_bundle = next(
        row for row in _load_jsonl(naive_path) if row.get("event") == "paired_bundle_summary"
    )
    if naive_bundle.get("implementation_tree_sha256") != implementation_hash:
        raise ValueError("naïve evidence does not share the release implementation tree")


def _load_jsonl(path: Path) -> tuple[JsonObject, ...]:
    return tuple(
        _object(json.loads(line), "evidence row")
        for line in path.read_text(encoding="utf-8").splitlines()
        if line.strip()
    )


def _load_object(path: Path) -> JsonObject:
    return _object(json.loads(path.read_text(encoding="utf-8")), path.name)


def _object(value: object, name: str) -> JsonObject:
    if not isinstance(value, dict) or any(not isinstance(key, str) for key in value):
        raise ValueError(f"{name} must be an object")
    return cast(JsonObject, value)


def _objects(value: object, name: str) -> tuple[JsonObject, ...]:
    if not isinstance(value, list):
        raise ValueError(f"{name} must be an array")
    return tuple(_object(item, name) for item in value)


def _string(value: object, name: str) -> str:
    if not isinstance(value, str) or not value:
        raise ValueError(f"{name} must be a non-empty string")
    return value


def _integer(value: object, name: str) -> int:
    if not isinstance(value, int) or isinstance(value, bool):
        raise ValueError(f"{name} must be an integer")
    return value
